    #[test]
    fn test_lombok_data_generation() {
        let mut cls = ClassInfo {
            fqn: "com.demo.User".into(),
            simple_name: "User".into(),
            package_name: "com.demo".into(),
            kind: ClassKind::Class,
            super_class: None,
            interfaces: vec![],
            methods: vec![],
            fields: vec![FieldInfo {
                name: "id".into(),
                field_type: TypeSignature::Long,
                is_static: false,
                is_public: false,
                is_final: false,
            }],
            source_path: None,
            is_public: true,
        };

        let src = "@Data\npublic class User { private Long id; }";
        process_lombok_annotations(&mut cls, src);

        assert!(cls.methods.iter().any(|m| m.name == "getId"));
        assert!(cls.methods.iter().any(|m| m.name == "setId"));
        assert!(cls.methods.iter().any(|m| m.name == "toString"));
    }

    #[tokio::test]
    async fn test_lombok_references_and_definition_linking() {
        use crate::syntax::JavaAst;
        use crate::classpath::ClasspathRegistry;
        use crate::semantic::SemanticContext;
        use std::sync::Arc;

        let code = r#"
            import lombok.Data;

            @Data
            public class User {
                private String username;

                public void test() {
                    String u = getUsername();
                    setUsername("admin");
                }
            }
        "#;
        let ast = JavaAst::parse(Arc::new(code.to_string())).expect("Parse code");
        let cp = ClasspathRegistry::new();
        let sem = SemanticContext::new(&ast, &cp).await;

        // Goto definition from getUsername() at row 8, col 31
        let def = sem.goto_definition(8, 31).await;
        assert!(def.is_some(), "Should find definition for getUsername()");
        let (_path, range) = def.unwrap();
        // Row 5 is 'private String username;' -> lines 5, cols 31-39
        assert_eq!(range.start.line, 5);

        // Find occurrences of username, getUsername, setUsername
        let field_occs = ast.find_all_occurrences("username");
        let get_occs = ast.find_all_occurrences("getUsername");
        let set_occs = ast.find_all_occurrences("setUsername");

        assert_eq!(field_occs.len(), 1);
        assert_eq!(get_occs.len(), 1);
        assert_eq!(set_occs.len(), 1);
    }

