use std::collections::HashMap;
use std::path::Path;
use crate::model::{ClassInfo, ClassKind, FieldInfo, MethodInfo, TypeSignature};

/// Parse key-value properties from lombok.config content
pub fn parse_lombok_config(content: &str) -> HashMap<String, String> {
    let mut map = HashMap::new();
    for line in content.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        if let Some((k, v)) = trimmed.split_once('=') {
            map.insert(k.trim().to_string(), v.trim().to_string());
        }
    }
    map
}

/// Find and load lombok.config from file path or parent directories
pub fn find_and_load_lombok_config<P: AsRef<Path>>(file_path: P) -> HashMap<String, String> {
    let mut curr = file_path.as_ref().parent();
    while let Some(dir) = curr {
        let config_file = dir.join("lombok.config");
        if config_file.exists() {
            if let Ok(content) = std::fs::read_to_string(&config_file) {
                return parse_lombok_config(&content);
            }
        }
        curr = dir.parent();
    }
    HashMap::new()
}

/// Augment ClassInfo with synthetic methods generated by Lombok annotations,
/// and return any synthetic companion classes (e.g. XxxBuilder generated by @Builder).
pub fn process_lombok_annotations(cls: &mut ClassInfo, source_text: &str) -> Vec<ClassInfo> {
    let mut synthetic_classes = Vec::new();

    if source_text.contains("@Value") {
        for f in &mut cls.fields {
            if !f.is_static {
                f.is_final = true;
            }
        }
    }

    let has_getter = source_text.contains("@Getter") || source_text.contains("@Data") || source_text.contains("@Value") || source_text.contains("@Accessors");
    let has_setter = (source_text.contains("@Setter") || source_text.contains("@Data") || source_text.contains("@Accessors")) && !source_text.contains("@Value");
    let has_no_args = source_text.contains("@NoArgsConstructor");
    let has_all_args = source_text.contains("@AllArgsConstructor");
    let has_required_args = source_text.contains("@RequiredArgsConstructor") || source_text.contains("@Value");
    let has_to_string = source_text.contains("@ToString") || source_text.contains("@Data") || source_text.contains("@Value");
    let has_equals_hash = source_text.contains("@EqualsAndHashCode") || source_text.contains("@Data") || source_text.contains("@Value");

    let mut is_chain = source_text.contains("@Accessors") && source_text.contains("chain");
    let mut is_fluent = source_text.contains("@Accessors") && source_text.contains("fluent");

    // Check lombok.config if source path is available
    if let Some(src_path) = &cls.source_path {
        let config = find_and_load_lombok_config(src_path);
        if config.get("lombok.accessors.chain").map(|v| v.as_str()) == Some("true") {
            is_chain = true;
        }
        if config.get("lombok.accessors.fluent").map(|v| v.as_str()) == Some("true") {
            is_fluent = true;
        }
    }

    // 1. Synthetic Getters & Setters
    for f in &cls.fields {
        let is_bool = matches!(f.field_type, TypeSignature::Boolean)
            || f.field_type.simple_name() == "boolean"
            || f.field_type.simple_name() == "Boolean";

        let capitalized = {
            let mut chars = f.name.chars();
            match chars.next() {
                Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
                None => f.name.clone(),
            }
        };

        // Also check if field itself has @Getter / @Setter in source text
        let field_has_getter = has_getter || source_text.contains(&format!("@Getter\n    private {} {}", f.field_type.simple_name(), f.name))
            || source_text.contains(&format!("@Getter private {} {}", f.field_type.simple_name(), f.name));
        let field_has_setter = has_setter || source_text.contains(&format!("@Setter\n    private {} {}", f.field_type.simple_name(), f.name))
            || source_text.contains(&format!("@Setter private {} {}", f.field_type.simple_name(), f.name));

        if field_has_getter {
            let getter_name = if is_fluent {
                f.name.clone()
            } else if is_bool {
                format!("is{}", capitalized)
            } else {
                format!("get{}", capitalized)
            };

            if !cls.methods.iter().any(|m| m.name == getter_name) {
                cls.methods.push(MethodInfo {
                    name: getter_name,
                    return_type: f.field_type.clone(),
                    parameters: vec![],
                    is_static: false,
                    is_public: true,
                    is_constructor: false,
                    javadoc: Some("Generated by Lombok @Getter".into()),
                    body: None,
                });
            }
        }

        if field_has_setter {
            let setter_name = if is_fluent {
                f.name.clone()
            } else {
                format!("set{}", capitalized)
            };

            let (ret_type, doc) = if is_chain || is_fluent {
                (
                    TypeSignature::Class(cls.simple_name.clone()),
                    "Generated by Lombok @Setter (chained)",
                )
            } else {
                (TypeSignature::Void, "Generated by Lombok @Setter")
            };

            if !cls.methods.iter().any(|m| m.name == setter_name) {
                cls.methods.push(MethodInfo {
                    name: setter_name,
                    return_type: ret_type,
                    parameters: vec![(f.name.clone(), f.field_type.clone())],
                    is_static: false,
                    is_public: true,
                    is_constructor: false,
                    javadoc: Some(doc.into()),
                    body: None,
                });
            }
        }
    }

    // 2. Synthetic Constructors
    let required_params: Vec<(String, TypeSignature)> = cls
        .fields
        .iter()
        .filter(|f| !f.is_static && (f.is_final || source_text.contains("@NonNull")))
        .map(|f| (f.name.clone(), f.field_type.clone()))
        .collect();

    let should_gen_required = has_required_args
        || (source_text.contains("@Data") && !has_no_args && !has_all_args && !required_params.is_empty());

    if should_gen_required && !required_params.is_empty() {
        if !cls.methods.iter().any(|m| m.is_constructor && m.parameters == required_params) {
            cls.methods.push(MethodInfo {
                name: "<init>".into(),
                return_type: TypeSignature::Void,
                parameters: required_params.clone(),
                is_static: false,
                is_public: true,
                is_constructor: true,
                javadoc: Some("Generated by Lombok @RequiredArgsConstructor".into()),
                body: None,
            });
        }
    }

    let should_gen_no_args = has_no_args || (source_text.contains("@Data") && !has_all_args && required_params.is_empty());
    if should_gen_no_args && !cls.methods.iter().any(|m| m.is_constructor && m.parameters.is_empty()) {
        cls.methods.push(MethodInfo {
            name: "<init>".into(),
            return_type: TypeSignature::Void,
            parameters: vec![],
            is_static: false,
            is_public: true,
            is_constructor: true,
            javadoc: Some("Generated by Lombok @NoArgsConstructor".into()),
            body: None,
        });
    }

    if has_all_args && !cls.fields.is_empty() {
        let all_params: Vec<(String, TypeSignature)> = cls
            .fields
            .iter()
            .filter(|f| !f.is_static)
            .map(|f| (f.name.clone(), f.field_type.clone()))
            .collect();
        if !cls.methods.iter().any(|m| m.is_constructor && m.parameters == all_params) {
            cls.methods.push(MethodInfo {
                name: "<init>".into(),
                return_type: TypeSignature::Void,
                parameters: all_params,
                is_static: false,
                is_public: true,
                is_constructor: true,
                javadoc: Some("Generated by Lombok @AllArgsConstructor".into()),
                body: None,
            });
        }
    }

    // 3. Synthetic toString()
    if has_to_string && !cls.methods.iter().any(|m| m.name == "toString") {
        cls.methods.push(MethodInfo {
            name: "toString".into(),
            return_type: TypeSignature::Class("java.lang.String".into()),
            parameters: vec![],
            is_static: false,
            is_public: true,
            is_constructor: false,
            javadoc: Some("Generated by Lombok @ToString".into()),
            body: None,
        });
    }

    // 4. Synthetic equals() and hashCode()
    if has_equals_hash {
        if !cls.methods.iter().any(|m| m.name == "equals") {
            cls.methods.push(MethodInfo {
                name: "equals".into(),
                return_type: TypeSignature::Boolean,
                parameters: vec![("o".into(), TypeSignature::Class("java.lang.Object".into()))],
                is_static: false,
                is_public: true,
                is_constructor: false,
                javadoc: Some("Generated by Lombok @EqualsAndHashCode".into()),
                body: None,
            });
        }
        if !cls.methods.iter().any(|m| m.name == "hashCode") {
            cls.methods.push(MethodInfo {
                name: "hashCode".into(),
                return_type: TypeSignature::Int,
                parameters: vec![],
                is_static: false,
                is_public: true,
                is_constructor: false,
                javadoc: Some("Generated by Lombok @EqualsAndHashCode".into()),
                body: None,
            });
        }
    }

    // 5. Synthetic @Builder & @SuperBuilder: builder() static method AND synthetic XxxBuilder ClassInfo
    let has_super_builder = source_text.contains("@SuperBuilder");
    let has_builder = source_text.contains("@Builder") || has_super_builder;
    let has_singular = source_text.contains("@Singular");

    if has_builder {
        let builder_type_name = format!("{}Builder", cls.simple_name);
        if !cls.methods.iter().any(|m| m.name == "builder") {
            cls.methods.push(MethodInfo {
                name: "builder".into(),
                return_type: TypeSignature::Class(builder_type_name.clone()),
                parameters: vec![],
                is_static: true,
                is_public: true,
                is_constructor: false,
                javadoc: Some("Generated by Lombok @Builder".into()),
                body: None,
            });
        }

        if has_super_builder && !cls.methods.iter().any(|m| m.name == "toBuilder") {
            cls.methods.push(MethodInfo {
                name: "toBuilder".into(),
                return_type: TypeSignature::Class(builder_type_name.clone()),
                parameters: vec![],
                is_static: false,
                is_public: true,
                is_constructor: false,
                javadoc: Some("Generated by Lombok @SuperBuilder".into()),
                body: None,
            });
        }

        // Generate full XxxBuilder companion ClassInfo
        let mut builder_methods = Vec::new();
        builder_methods.push(MethodInfo {
            name: "<init>".into(),
            return_type: TypeSignature::Void,
            parameters: vec![],
            is_static: false,
            is_public: true,
            is_constructor: true,
            javadoc: Some(format!("Constructs a new {} instance", builder_type_name)),
            body: None,
        });

        for f in &cls.fields {
            builder_methods.push(MethodInfo {
                name: f.name.clone(),
                return_type: TypeSignature::Class(builder_type_name.clone()),
                parameters: vec![(f.name.clone(), f.field_type.clone())],
                is_static: false,
                is_public: true,
                is_constructor: false,
                javadoc: Some(format!("Sets the value for field '{}'", f.name)),
                body: None,
            });

            // If @Singular is used on collection field, add singular and clear methods
            let singular_name = if f.name.ends_with("ies") {
                Some(format!("{}y", &f.name[..f.name.len() - 3]))
            } else if f.name.ends_with('s') && f.name.len() > 1 {
                Some(f.name[..f.name.len() - 1].to_string())
            } else {
                None
            };
            if has_singular && singular_name.is_some() {
                let s_name = singular_name.unwrap();
                let capitalized = {
                    let mut chars = f.name.chars();
                    match chars.next() {
                        Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
                        None => f.name.clone(),
                    }
                };
                builder_methods.push(MethodInfo {
                    name: s_name.clone(),
                    return_type: TypeSignature::Class(builder_type_name.clone()),
                    parameters: vec![(s_name, TypeSignature::Class("java.lang.Object".into()))],
                    is_static: false,
                    is_public: true,
                    is_constructor: false,
                    javadoc: Some(format!("Singular adder for field '{}'", f.name)),
                    body: None,
                });
                builder_methods.push(MethodInfo {
                    name: format!("clear{}", capitalized),
                    return_type: TypeSignature::Class(builder_type_name.clone()),
                    parameters: vec![],
                    is_static: false,
                    is_public: true,
                    is_constructor: false,
                    javadoc: Some(format!("Clears all entries for field '{}'", f.name)),
                    body: None,
                });
            }
        }

        builder_methods.push(MethodInfo {
            name: "build".into(),
            return_type: TypeSignature::Class(cls.simple_name.clone()),
            parameters: vec![],
            is_static: false,
            is_public: true,
            is_constructor: false,
            javadoc: Some(format!("Builds and returns an instance of {}", cls.simple_name)),
            body: None,
        });

        builder_methods.push(MethodInfo {
            name: "toString".into(),
            return_type: TypeSignature::Class("java.lang.String".into()),
            parameters: vec![],
            is_static: false,
            is_public: true,
            is_constructor: false,
            javadoc: Some(format!("Returns string representation of {}", builder_type_name)),
            body: None,
        });

        let builder_fqn = if cls.package_name.is_empty() {
            builder_type_name.clone()
        } else {
            format!("{}.{}", cls.package_name, builder_type_name)
        };

        synthetic_classes.push(ClassInfo {
            fqn: builder_fqn,
            simple_name: builder_type_name,
            package_name: cls.package_name.clone(),
            kind: ClassKind::Class,
            super_class: None,
            interfaces: Vec::new(),
            methods: builder_methods,
            fields: Vec::new(),
            source_path: cls.source_path.clone(),
            is_public: true,
        });
    }

    // 5.5 Synthetic @FieldNameConstants
    if source_text.contains("@FieldNameConstants") {
        let fields_class_name = format!("{}$Fields", cls.simple_name);
        let fields_fqn = if cls.package_name.is_empty() {
            fields_class_name.clone()
        } else {
            format!("{}.{}", cls.package_name, fields_class_name)
        };
        let mut static_fields = Vec::new();
        for f in &cls.fields {
            static_fields.push(FieldInfo {
                name: f.name.clone(),
                field_type: TypeSignature::Class("java.lang.String".into()),
                is_static: true,
                is_public: true,
                is_final: true,
            });
        }
        synthetic_classes.push(ClassInfo {
            fqn: fields_fqn,
            simple_name: "Fields".into(),
            package_name: cls.package_name.clone(),
            kind: ClassKind::Class,
            super_class: None,
            interfaces: Vec::new(),
            methods: Vec::new(),
            fields: static_fields,
            source_path: cls.source_path.clone(),
            is_public: true,
        });
    }

    // 6. Synthetic @Value: makes fields final & adds getters
    let has_value = source_text.contains("@Value");
    if has_value {
        for f in &cls.fields {
            let capitalized = {
                let mut chars = f.name.chars();
                match chars.next() {
                    Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
                    None => f.name.clone(),
                }
            };
            let getter_name = format!("get{}", capitalized);
            if !cls.methods.iter().any(|m| m.name == getter_name) {
                cls.methods.push(MethodInfo {
                    name: getter_name,
                    return_type: f.field_type.clone(),
                    parameters: vec![],
                    is_static: false,
                    is_public: true,
                    is_constructor: false,
                    javadoc: Some("Generated by Lombok @Value".into()),
                    body: None,
                });
            }
        }
    }

    // 6. Synthetic Logging Annotations: @Slf4j, @CommonsLog, @Log4j2
    let has_slf4j = source_text.contains("@Slf4j");
    let has_commons_log = source_text.contains("@CommonsLog");
    let has_log4j2 = source_text.contains("@Log4j2");
    if (has_slf4j || has_commons_log || has_log4j2) && !cls.fields.iter().any(|f| f.name == "log") {
        let logger_type = if has_slf4j {
            "org.slf4j.Logger"
        } else if has_commons_log {
            "org.apache.commons.logging.Log"
        } else {
            "org.apache.logging.log4j.Logger"
        };

        cls.fields.push(crate::model::FieldInfo {
            name: "log".into(),
            field_type: TypeSignature::Class(logger_type.into()),
            is_static: true,
            is_public: false,
            is_final: true,
        });
    }

    // 7. Synthetic MyBatis-Plus BaseMapper<T> Methods
    let is_mp_mapper = cls.interfaces.iter().any(|i| i == "BaseMapper" || i.ends_with(".BaseMapper"))
        || source_text.contains("extends BaseMapper");
    if is_mp_mapper {
        let mp_methods = [
            ("insert", TypeSignature::Int, vec![("entity".into(), TypeSignature::Class("T".into()))], "Insert an entity"),
            ("deleteById", TypeSignature::Int, vec![("id".into(), TypeSignature::Class("java.io.Serializable".into()))], "Delete entity by primary key"),
            ("deleteByMap", TypeSignature::Int, vec![("columnMap".into(), TypeSignature::Class("java.util.Map".into()))], "Delete entities by column map conditions"),
            ("delete", TypeSignature::Int, vec![("wrapper".into(), TypeSignature::Class("com.baomidou.mybatisplus.core.conditions.Wrapper".into()))], "Delete entities by wrapper condition"),
            ("updateById", TypeSignature::Int, vec![("entity".into(), TypeSignature::Class("T".into()))], "Update entity by primary key"),
            ("update", TypeSignature::Int, vec![("entity".into(), TypeSignature::Class("T".into())), ("updateWrapper".into(), TypeSignature::Class("com.baomidou.mybatisplus.core.conditions.Wrapper".into()))], "Update entity by wrapper condition"),
            ("selectById", TypeSignature::Class("T".into()), vec![("id".into(), TypeSignature::Class("java.io.Serializable".into()))], "Select entity by primary key"),
            ("selectBatchIds", TypeSignature::Class("java.util.List<T>".into()), vec![("idList".into(), TypeSignature::Class("java.util.Collection".into()))], "Select entities by primary key batch"),
            ("selectByMap", TypeSignature::Class("java.util.List<T>".into()), vec![("columnMap".into(), TypeSignature::Class("java.util.Map".into()))], "Select entities by column map conditions"),
            ("selectOne", TypeSignature::Class("T".into()), vec![("queryWrapper".into(), TypeSignature::Class("com.baomidou.mybatisplus.core.conditions.Wrapper".into()))], "Select single entity by query wrapper"),
            ("selectCount", TypeSignature::Long, vec![("queryWrapper".into(), TypeSignature::Class("com.baomidou.mybatisplus.core.conditions.Wrapper".into()))], "Count entities by query wrapper"),
            ("selectList", TypeSignature::Class("java.util.List<T>".into()), vec![("queryWrapper".into(), TypeSignature::Class("com.baomidou.mybatisplus.core.conditions.Wrapper".into()))], "Select entities by query wrapper"),
            ("selectMaps", TypeSignature::Class("java.util.List<java.util.Map<String, Object>>".into()), vec![("queryWrapper".into(), TypeSignature::Class("com.baomidou.mybatisplus.core.conditions.Wrapper".into()))], "Select map records by query wrapper"),
            ("selectPage", TypeSignature::Class("P".into()), vec![("page".into(), TypeSignature::Class("com.baomidou.mybatisplus.core.metadata.IPage".into())), ("queryWrapper".into(), TypeSignature::Class("com.baomidou.mybatisplus.core.conditions.Wrapper".into()))], "Select paginated records by query wrapper"),
        ];

        for (m_name, ret, params, doc) in mp_methods {
            if !cls.methods.iter().any(|m| m.name == m_name) {
                cls.methods.push(MethodInfo {
                    name: m_name.into(),
                    return_type: ret,
                    parameters: params,
                    is_static: false,
                    is_public: true,
                    is_constructor: false,
                    javadoc: Some(format!("Generated by MyBatis-Plus BaseMapper: {}", doc)),
                    body: None,
                });
            }
        }
    }

    synthetic_classes
}

